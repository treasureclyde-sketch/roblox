local function pick(list)
	if not list or #list == 0 then return nil end
	return list[math.random(1, #list)]
end

-- Dialogue.line("friendly", "hint") -> случайная строка этой категории (или nil)
function Dialogue.line(mood, category)
	local m = Dialogue.lines[mood]
	if not m then return nil end
	return pick(m[category])
end

return Dialogue
